/** Numeracion siguiente para el formulario de postulacion publica. */
export const PROXIMO_ID_CANDIDATO = CANDIDATOS.length + 1;

export function obtenerCandidato(idCandidato) {
  return CANDIDATOS.find((candidato) => candidato.id === Number(idCandidato)) ?? null;
}

export function nombreCompleto(candidato) {
  if (!candidato) return 'Candidato no encontrado';
  return `${candidato.nombres} ${candidato.apellido_paterno} ${candidato.apellido_materno ?? ''}`.trim();
}

export function inicialesCandidato(candidato) {
  if (!candidato) return '??';
  return `${candidato.nombres.charAt(0)}${candidato.apellido_paterno.charAt(0)}`.toUpperCase();
}